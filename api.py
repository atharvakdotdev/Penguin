    @staticmethod
    def _is_controller_prompt(message):
        if not isinstance(message, str):
            return False
        cleaned = message.strip()
        return (
            cleaned.startswith("The requested command has finished.")
            and "Choose the next diagnostic step based on the above output." in cleaned
        )

    @staticmethod
    def _is_internal_investigation_payload(message):
        if not isinstance(message, str):
            return False
        cleaned = message.strip()
        if not (cleaned.startswith("{") and cleaned.endswith("}")):
            return False
        try:
            payload = json.loads(cleaned)
        except json.JSONDecodeError:
            return False
        return isinstance(payload, dict) and any(key in payload for key in ["issue", "summary", "facts", "hypotheses", "executed_commands", "next_goal", "confidence"])

    def _sanitize_chat_history(self, history):
        if not isinstance(history, list):
            return []

        cleaned = []
        for entry in history:
            if not isinstance(entry, dict):
                continue
            role = entry.get("role")
            if role == "system":
                continue
            if role == "user":
                content = entry.get("content")
                if self._is_controller_prompt(content):
                    continue
            cleaned.append(copy.deepcopy(entry))
        return cleaned


    def list_models(self):
        installed_models = []
        try:
            models = ollama.list()
            installed_models = [model.model for model in models.models if model.model]
        except Exception:
            installed_models = []

        if self.current_chat_model and self.current_chat_model not in installed_models:
            installed_models.insert(0, self.current_chat_model)

        if not installed_models:
            installed_models = [self.current_chat_model or self.default_model or DEFAULT_MODEL]

        unique_models = []
        for model_name in installed_models:
            if model_name not in unique_models:
                unique_models.append(model_name)

        return unique_models

