    def testHypothesis(self,next_step):
        self.command_outputs = []
        
        for hypothesis in self.hypotheses["hypotheses"]:

            self.Testcommands = self.investigation.generateCommandsToTestHypothesis(
                problem_statement=self.problem_statenment,
                hypothesis=hypothesis,
                model_name=self.current_chat_model
            )
            if self.Testcommands is None:
                return
            
            tests = self.Testcommands.get("tests", [])
            for test in tests:
                if isinstance(test, dict):
                    test.setdefault("command_id", str(uuid4()))
                    if not self.auto_allow:
                        self._pending_approvals.setdefault(test["command_id"], threading.Event())
            self.sendEvent(
            data={
                "hypothesis": hypothesis,
                "tests": tests,
                "auto_allow": self.auto_allow,
            },
            Data_type="testing_hypothesis"
            )

            # input("Press Enter to execute the tests...")

            for test in tests:
                result = self.run_command(test["command"], command_id=test.get("command_id"))
                self.command_outputs.append(result)
                self.sendEvent(
                    data=self.command_outputs,
                    Data_type="command_outputs"
                )

            self.sendEvent(
                data={"hypothesis": hypothesis},
                Data_type="hypothesis_tested"
            )
        self.state = next_step
        self.controller(next_step=next_step)

