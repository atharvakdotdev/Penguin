    def run_command_flag(self, command, use_sudo=False):
        """Approve a command that is already waiting in the investigation loop."""
        if not isinstance(command, str) or not command.strip():
            return {"success": False, "output": "", "error": "No command supplied", "return_code": -1}

        if self._shutdown_event.is_set():
            return {"success": False, "output": "", "error": "Command is no longer pending", "return_code": -1}

        approval = self._pending_approvals.get(command)
        if approval is not None:
            approval.set()
            return {"success": True, "output": "", "error": "", "return_code": 0}

        with self._active_runs_lock:
            runs = list(self._active_runs.values())

        for run in reversed(runs):
            if run._shutdown_event.is_set():
                continue
            approval = run._pending_approvals.get(command)
            if approval is not None:
                approval.set()
                return {"success": True, "output": "", "error": "", "return_code": 0}
        return {"success": False, "output": "", "error": "Command is no longer pending", "return_code": -1}

    def stop_agent(self):
        """Stop active generation or approval waits and persist current progress."""
        self._clear_pending_approvals(shutdown=True)
        with self._active_runs_lock:
            active_runs = list(self._active_runs.values())

        for run in active_runs:
            stream = getattr(run, "_active_stream", None)
            close = getattr(stream, "close", None)
            if callable(close):
                try:
                    close()
                except (RuntimeError, ValueError):
                    # A stream can already be unwinding from the generator loop; a
                    # shutdown should remain best-effort instead of crashing the UI.
                    pass
                finally:
                    run._active_stream = None

        if active_runs:
            for run in active_runs:
                run._investigation_running = False
                run.save_current_session()
        else:
            self.save_current_session()
        return {"status": "stopped"}
    def _record_command(self, command, success, output):
        executions = self.investigating_obj.setdefault("executed_commands", [])
        execution = {
            "command": command,
            "success": success,
            "output": output,
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "session_id": self._event_session_id(),
        }
        executions.append(execution)

    def _should_run_command(self, command):
        executions = self.investigating_obj.get("executed_commands", [])
        if not executions:
            return True

        # Consider only executions from the current active session when
        # deciding whether a command was just-run. This avoids treating
        # identical commands run in other sessions as if they were run
        # immediately prior in this session.
        if self.active_session_id is None:
            # no active session: fall back to checking the very last entry
            last_entry = executions[-1]
            return not (isinstance(last_entry, dict) and last_entry.get("command") == command)

        # Walk backwards to find the most recent execution for this session
        last_entry_for_session = None
        for entry in reversed(executions):
            if not isinstance(entry, dict):
                continue
            if entry.get("session_id") == self.active_session_id:
                last_entry_for_session = entry
                break

        if last_entry_for_session is None:
            # no previous executions in this session
            return True

        return not (last_entry_for_session.get("command") == command)

    def run_command(self, command, use_sudo=False, command_id=None):
        """Execute a shell command after explicit approval and emit output through the event stream."""
        command_id = command_id or command
        approval = None
        if not self.auto_allow:
            approval = self._pending_approvals.setdefault(command_id, threading.Event())
            try:
                while not approval.wait(timeout=0.5):
                    if self._shutdown_event.is_set():
                        return {
                            "success": False,
                            "output": "",
                            "error": "Command approval cancelled because the investigation stopped.",
                            "return_code": -1,
                        }
            finally:
                self._pending_approvals.pop(command_id, None)

        try:
            if use_sudo:
                command = f"sudo {command}"

            result = subprocess.run(
                command,
                shell=True,
                capture_output=True,
                text=True,
                timeout=120,
            )
            output = result.stdout or result.stderr or ""
            self._record_command(command, result.returncode == 0, output)
            self._remove_command_from_history(command)

            output_payload = {
                "command": command,
                "success": result.returncode == 0,
                "output": result.stdout or "",
                "error": result.stderr or "",
                "return_code": result.returncode,
                "timestamp": datetime.now(timezone.utc).isoformat(),
                "session_id": self._event_session_id(),
            }

            if self.windowobj is not None:
                self.sendEvent([output_payload], "command_outputs")

            return {
                "success": result.returncode == 0,
                "output": output,
                "error": result.stderr,
                "return_code": result.returncode,
            }
        except subprocess.TimeoutExpired:
            self._record_command(command, False, "Command timed out after 30 seconds")
            self._remove_command_from_history(command)
            error = "Command timed out after 30 seconds"
            if self.windowobj is not None:
                self.sendEvent([
                    {
                        "command": command,
                        "success": False,
                        "output": "",
                        "error": error,
                        "return_code": -1,
                        "timestamp": datetime.now(timezone.utc).isoformat(),
                        "session_id": self._event_session_id(),
                    }
                ], "command_outputs")
            return {
                "success": False,
                "output": "",
                "error": error,
                "return_code": -1,
            }
        except Exception as e:
            self._record_command(command, False, str(e))
            self._remove_command_from_history(command)
            error = str(e)
            if self.windowobj is not None:
                self.sendEvent([
                    {
                        "command": command,
                        "success": False,
                        "output": "",
                        "error": error,
                        "return_code": -1,
                        "timestamp": datetime.now(timezone.utc).isoformat(),
                        "session_id": self._event_session_id(),
                    }
                ], "command_outputs")
            return {"success": False, "output": "", "error": error, "return_code": -1}
        finally:
            if approval is not None:
                self._pending_approvals.pop(command_id, None)

    def sendEvent(self,data,Data_type):
        session_id = self._event_session_id()
        event_obj = {
            "data": data,
            "type": Data_type.lower().replace(" ", "_"),
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "session_id": session_id,
        }
        if session_id == self.active_session_id:
            self.runtime_state = self._runtime_snapshot()
            self.chat_history.append({"role": "system", "content": json.dumps(event_obj, ensure_ascii=False)})
            self.save_current_session()
        else:
            self._save_event_to_session(session_id, event_obj)
        if self.windowobj is not None:
            self.windowobj.evaluate_js(f"window.handleInvestigationEvent({json.dumps(event_obj)})")

            
    def contradictionloop(self):
        print(f"[model] CheckHypothesisContradiction: {self.current_chat_model}", flush=True)

        self.contradistion_bool= self.investigation.CheckHypothesisContradiction(
            model_name=self.current_chat_model,
            command_outputs=self.result,
            hypothesis=self.hypothesis
        )
        if self.contradistion_bool is None:
            return
        if self.contradistion_bool["contradicts"]:
            self.state = "HypothesisUpdate"
            self.controller(next_step="HypothesisUpdate")
        else:
            self.state = "Solve"
            self.controller(next_step="Solve")

    def verificationloop(self):
        print(f"[model] Verification command: {self.current_chat_model}", flush=True)
        self.verification = self.investigation.verifiRemediation(
            problem_statement=self.problem_statenment,
            model_name=self.current_chat_model,
            command_outputs=self.command_outputs,
        )
        if self.verification is None:
            return
        step = self.verification.get("step") if isinstance(self.verification, dict) else None

        if isinstance(step, dict):
            step.setdefault("command_id", str(uuid4()))
            if not self.auto_allow:
                self._pending_approvals.setdefault(step["command_id"], threading.Event())

        self.sendEvent(
            data={"step": step, "auto_allow": self.auto_allow},
            Data_type="verification",
        )
        verification_result = self.run_command(step["command"], command_id=step.get("command_id"))

        print(f"[model] Verification evaluator: {self.current_chat_model}", flush=True)

        self.evaluation = self.investigation.verifi(
            problem_statement=self.problem_statenment,
            model_name=self.current_chat_model,
            command_outputs=verification_result,
        )
        if self.evaluation is None:
            return
        if self.evaluation.get("solved") is True:
            self.state = "IssueResolved"
            self.controller(next_step="IssueResolved")
        else:
            self.state = "Solve"
            self.controller(next_step="Solve")

    def issueResolved(self):
        self.sendEvent(
            data={
                "title": "Issue Resolved",
                "message": "The issue has been resolved and verified.",
                "summary": self.solution if isinstance(self.solution, dict) else self.verification,
                "solved": True,
            },
            Data_type="issue_resolved",
        )

    def solver(self):
        print(f"[model] Solve: {self.current_chat_model}", flush=True)
        self.solution = self.investigation.generateSolution(
        problem_statement=self.problem_statenment,
        facts=self.facts,
        model_name=self.current_chat_model,
        relevant_command_outputs=self.command_outputs,hypothesis=self.hypothesis
        )
        if self.solution is None:
            return
        step = self.solution.get("step") if isinstance(self.solution, dict) else None
        if isinstance(step, dict):
            step.setdefault("command_id", str(uuid4()))
            if not self.auto_allow:
                self._pending_approvals.setdefault(step["command_id"], threading.Event())

        self.sendEvent(
                    data={"step": step, "auto_allow": self.auto_allow, **({} if not isinstance(self.solution, dict) else {k: v for k, v in self.solution.items() if k != "step"})},
                    Data_type="solution"
                )
        self.result = self.run_command(step["command"], command_id=step.get("command_id"))

        if self.result["return_code"] == 0:
            self.state = "Verification"
            self.controller(next_step="Verification")
        else:
            self.state = "CheckHypothesisContradiction"
            self.controller(next_step="CheckHypothesisContradiction")
    
    def UpdateHypothesis(self):
        print(f"[model] UpdateHypothesis: {self.current_chat_model}", flush=True)
        self.hypotheses = self.investigation.generateHypothesis(user_request=self.problem_statenment,model_name=self.current_chat_model,facts=self.facts,command_outputs=self.command_outputs)
        if self.hypotheses is None:
            return
        self.sendEvent(
            data=self.hypotheses,
            Data_type="hypotheses"
        )
        
        SOLVER_THRESHOLD = 0.9
        for hypothesis in self.hypotheses["hypotheses"]:
            if hypothesis["confidence"] >= SOLVER_THRESHOLD:
                self.hypothesis = hypothesis
                self.state = "Solve"
                self.controller(next_step="Solve")
            else:
                self.state = "Hypothesis"
                self.controller(next_step="Hypothesis")
        
