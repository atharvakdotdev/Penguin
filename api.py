    def controller(self,user_input=None,attached_path="",attached="",next_step="ProblemStatement",history=None):

        if history == None and user_input != None:
            self.sendEvent(
                        data=user_input,
                        Data_type="user"
                    )

        if isinstance(user_input, str) and user_input.strip():
            self._shutdown_event.clear()

        if self._abort_if_stopped():
            return
    
        if user_input:
            self.user_msg.append(user_input)

        
        if len(self.user_msg) > 1 and user_input is not None and self.problem_statenment != None:
            self.state = "Decision"

        if self.state == "ProblemStatement":
            self.StartInvetigation(user_input,attached_path,attached,next_step="Hypothesis")

        elif self.state == "Hypothesis":
            self.GenerateHypothesis(next_step="TestingHypothesis")

        elif self.state == "TestingHypothesis":
            self.testHypothesis(next_step="Facts")

        
        elif self.state == "Facts":
            self.GenerateFacts(next_step="HypothesisUpdate")

        elif self.state == "HypothesisUpdate":
            self.UpdateHypothesis()

        elif self.state == "Solve":
            self.solver()

        elif self.state == "Verification":
            self.verificationloop()

        elif self.state == "CheckHypothesisContradiction":
            self.contradictionloop()

        elif self.state == "IssueResolved":
            self.issueResolved()
        elif self.state == "Decision":
            decision = self.generateDecisionOnMsg(user_input)

            if decision["action"] == "continue":
                self.controller(next_step=self.state)
                return

            if decision["action"] == "reassess":
                affected = [
                    item for item in decision.get("affected", [])
                    if item in INVESTIGATION_ORDER
                ]

                if not affected:
                    self.controller(next_step=self.state)
                    return

                highest_affected = min(
                    affected,
                    key=lambda x: INVESTIGATION_ORDER.index(x)
                )

                self.state = AFFECTED_TO_STATE[highest_affected]
                self.controller(next_step=self.state)
